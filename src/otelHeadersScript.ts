import { PLAN_HEADER, PROMPTSTER_DIR_NAME, REPO_HEADER, WORKDIR_HEADER } from './constants.js';

/**
 * The `otelHeadersHelper` script, written to ~/.promptster/otel-headers.mjs at
 * install time (both tiers). Claude Code runs it in the session's working
 * directory and merges its stdout JSON object onto every OTLP export as headers.
 *
 * Like the spool script, the installer owns this file end to end: it writes it,
 * `--print` names it, and `--uninstall` removes it. A helper pointing at a file
 * that does not exist is a broken install that looks fine in settings.json.
 *
 * Properties that matter more than anything it does:
 *   1. It ALWAYS exits 0 and prints exactly one JSON object. Its stdout is parsed
 *      by the exporter; anything else on it risks the export itself.
 *   2. A credential never leaves the machine. An https remote can carry a token
 *      in its userinfo (`https://user:ghp_x@github.com/...`); that is stripped
 *      before the value is ever written to stdout.
 *   3. The workdir is HOME-RELATIVE or empty. An absolute path carries the OS
 *      username, so a cwd outside home is sent as ''.
 *   4. The plan header carries pattern-clamped plan strings only (see
 *      PLAN_HEADER). ~/.claude.json also holds the engineer's email and name;
 *      only the named oauthAccount fields are read, and each must match a
 *      lower-case token pattern or it is dropped.
 *   5. Header values are printable ASCII. A raw non-ASCII byte in a header value
 *      can make an HTTP client reject the whole request, so anything outside
 *      0x20-0x7e is percent-encoded (`encodeURIComponent`) rather than sent raw.
 */
export const OTEL_HEADERS_SCRIPT_SOURCE = `#!/usr/bin/env node
// Generated by @promptster/setup — do not edit. Remove with: npx @promptster/setup --uninstall
// Claude Code otelHeadersHelper: prints {"${REPO_HEADER}": <origin url>, "${WORKDIR_HEADER}": <cwd relative to ~>}.
// Lives at ~/${PROMPTSTER_DIR_NAME}/. Exits 0 unconditionally and prints exactly one JSON object.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

function headerSafe(s) {
  return String(s).replace(/[^\\x20-\\x7e]/gu, (ch) => {
    try {
      return encodeURIComponent(ch);
    } catch {
      return '';
    }
  });
}

// Strip userinfo that could be a credential. http(s): drop it entirely (a token
// can sit in the username alone). Any other scheme://: keep the user, drop a
// password. scp-style git@host:path has no secret and is left verbatim.
function stripCredentials(url) {
  const m = /^([a-z][a-z0-9+.-]*:\\/\\/)([^/?#]*)@(.*)$/is.exec(url);
  if (!m) return url;
  const [, scheme, userinfo, rest] = m;
  if (/^https?:\\/\\//i.test(scheme)) return scheme + rest;
  const colon = userinfo.indexOf(':');
  return colon >= 0 ? scheme + userinfo.slice(0, colon) + '@' + rest : url;
}

function repo() {
  try {
    const out = execFileSync('git', ['remote', 'get-url', 'origin'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: 3000,
      windowsHide: true,
    });
    return stripCredentials(String(out).trim());
  } catch {
    return '';
  }
}

function workdir() {
  try {
    const win = process.platform === 'win32';
    const norm = (p) => {
      let s = String(p).replace(/\\\\/g, '/');
      while (s.length > 1 && s.endsWith('/') && !/^[a-z]:\\/$/i.test(s)) s = s.slice(0, -1);
      return s;
    };
    const h = norm(os.homedir());
    const c = norm(process.cwd());
    const eq = (a, b) => (win ? a.toLowerCase() === b.toLowerCase() : a === b);
    if (!h || h === '/') return '';
    if (eq(c, h)) return '~';
    const prefix = h + '/';
    if (c.length > prefix.length && eq(c.slice(0, prefix.length), prefix)) {
      return '~/' + c.slice(prefix.length);
    }
    return '';
  } catch {
    return '';
  }
}

// Lower-case and pattern-clamp a vendor string; '' when it does not match.
function token(v, max) {
  const s = typeof v === 'string' ? v.trim().toLowerCase() : '';
  return new RegExp('^[a-z0-9_-]{1,' + max + '}$').test(s) ? s : '';
}

function plan() {
  const dir = process.env.CLAUDE_CONFIG_DIR;
  const file = dir ? path.join(dir, '.claude.json') : path.join(os.homedir(), '.claude.json');
  let raw;
  try {
    raw = readFileSync(file, 'utf8');
  } catch (e) {
    // Only a missing file is an absence; a denied or failed read is a problem.
    return e && e.code === 'ENOENT' ? 'absent' : 'unreadable';
  }
  let a;
  try {
    a = JSON.parse(raw).oauthAccount;
  } catch {
    return 'unreadable';
  }
  // An API-key login has no oauthAccount: an observed absence, not "free".
  if (!a || typeof a !== 'object') return 'absent';
  const parts = [
    ['p', token(a.organizationType, 32)],
    ['r', token(a.userRateLimitTier, 64) || token(a.organizationRateLimitTier, 64)],
    ['s', token(a.seatTier, 32)],
    ['b', token(a.billingType, 32)],
    ['o', typeof a.hasExtraUsageEnabled === 'boolean' ? (a.hasExtraUsageEnabled ? '1' : '0') : ''],
    ['t', Number.isFinite(a.profileFetchedAt) && a.profileFetchedAt > 0 ? String(Math.floor(a.profileFetchedAt / 1000)) : ''],
  ];
  return parts.filter(([, v]) => v).map(([k, v]) => k + '=' + v).join(';');
}

let body;
try {
  body = JSON.stringify({
    '${REPO_HEADER}': headerSafe(repo()),
    '${WORKDIR_HEADER}': headerSafe(workdir()),
    '${PLAN_HEADER}': headerSafe(plan()),
  });
} catch {
  body = JSON.stringify({ '${REPO_HEADER}': '', '${WORKDIR_HEADER}': '', '${PLAN_HEADER}': '' });
}
try {
  process.stdout.write(body);
} catch {
  // Nothing useful left to do.
}
process.exitCode = 0;
`;

import { PROMPTSTER_DIR_NAME } from './constants.js';

/**
 * The tier-B spool script, written to ~/.promptster/spool.mjs at install time.
 *
 * A hook entry pointing at a file that does not exist is a broken install that
 * looks fine in settings.json, so the installer owns this artifact end to end:
 * it writes it, `--print` names it, and `--uninstall` removes it.
 *
 * Two properties matter more than anything it does:
 *   1. It ALWAYS exits 0. A hook that can fail is a hook that can wedge someone's
 *      session, and no telemetry is worth that.
 *   2. It only appends locally. Shipping the spool is a separate concern with its
 *      own retry and backoff; a hook is the wrong place to do network I/O.
 */
export const SPOOL_SCRIPT_VERSION = 1;

export const SPOOL_SCRIPT_SOURCE = `#!/usr/bin/env node
// Generated by @promptster/setup — do not edit. Remove with: npx @promptster/setup --uninstall
// Appends one JSON line per Claude Code hook event to ~/${PROMPTSTER_DIR_NAME}/spool/<date>.jsonl.
// Exits 0 unconditionally: a hook must never be able to break a session.
import { appendFileSync, mkdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const argv = process.argv.slice(2);
const eventIdx = argv.indexOf('--event');
const event = eventIdx >= 0 ? (argv[eventIdx + 1] ?? 'unknown') : 'unknown';

let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (c) => {
  // Cap what we buffer. A pathological tool_response should not become a memory event.
  if (raw.length < 1_000_000) raw += c;
});
process.stdin.on('end', () => {
  try {
    const dir = join(homedir(), '${PROMPTSTER_DIR_NAME}', 'spool');
    mkdirSync(dir, { recursive: true });
    const day = new Date().toISOString().slice(0, 10);
    let payload = null;
    try {
      payload = raw.trim() === '' ? null : JSON.parse(raw);
    } catch {
      payload = null;
    }
    const line = JSON.stringify({ v: ${SPOOL_SCRIPT_VERSION}, event, ts: new Date().toISOString(), payload });
    appendFileSync(join(dir, day + '.jsonl'), line + '\\n');
  } catch {
    // Swallow. See the header: exit 0 or nothing.
  }
  process.exit(0);
});
process.stdin.on('error', () => process.exit(0));
`;
